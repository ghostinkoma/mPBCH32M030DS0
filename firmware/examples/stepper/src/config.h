/*
 * ---- ステッピングモーターの設定例 (代表値。必ず手元のモーターのデータシート・銘板で確認すること) ----------
 * 電圧モードなので duty = 電流 × 巻線抵抗 ÷ VBUS で決まる。巻線抵抗はテスターで A+〜A− を測れば分かる。
 * 高速では逆起電力とインダクタンスで電流が減る (トルクが落ちる) → 速さが要るときは VBUS を上げる。
 *
 *  形式                         角度   定格電流  巻線抵抗  CFG_COIL_MA  CFG_COIL_R_MOHM  分割  加速度 (µstep/s²)
 *  NEMA17 (42mm, 例 17HS4401)  1.8°   1.7A      1.5Ω      1200〜1500   1500             16    40000
 *  NEMA17 薄型 (例 17HS08)     1.8°   1.0A      3.5Ω       700〜 900   3500             16    30000
 *  NEMA17 高トルク (例 17HS19) 1.8°   2.0A      1.4Ω      1500〜1800   1400             16    40000
 *  NEMA17 0.9° (400 歩/回転)   0.9°   1.7A      1.6Ω      1200         1600             8     40000  ※ STEPS_PER_REV 400
 *  NEMA14 (35mm)               1.8°   0.4〜1A   〜10Ω      300〜 800   (実測)           16    20000
 *  NEMA23 (57mm)               1.8°   2.8A      0.9Ω      2000〜2500    900             8     30000  ※ 子基板 A は約 5A/相まで
 *  PM 型小型 (15〜20mm, カメラ・プリンタ用) 18°/20 歩  0.1〜0.3A  10〜40Ω  100〜250  (実測)  8〜16  5000
 *  28BYJ-48 (5V ユニポーラを中点線を切ってバイポーラ化) 2048 歩/回転 (減速 1/64)  約 50Ω  約 100mA  (実測)  4〜8  2000
 *
 * ・定格電流の 70〜90% で使うと発熱が少ない。停止中は CFG_HOLD_PCT で下げる。
 * ・VBUS 12V で 1.5A × 1.5Ω = 2.25V → duty 約 19%。duty の分解能 (20kHz で 1/1800) を考えると, 小さすぎる duty で
 *   1/64 以上の分割は効きにくい → 巻線抵抗の大きいモーターや低い VBUS で細かい分割を使う。
 * ・マイクロステップは 1〜128 (2 のべき乗)。sin 表はフラッシュ 258 バイトで, 分割によらず RAM は増えない。
 * ・最高速度は PWM 周波数 [フルステップ/s] (20kHz, 200 歩/回転で 6000rpm) だが, 実際はトルクで頭打ち (数百 rpm)。
 */
#define CFG_STEPS_PER_REV   200u        /* フルステップ数 / 回転 (1.8° = 200, 0.9° = 400) */
#define CFG_MICROSTEP       16u         /* マイクロステップ分割 1〜128 (2 のべき乗) */
#define CFG_COIL_MA         800u        /* 相電流 (ピーク) [mA] */
#define CFG_COIL_R_MOHM     2800u       /* 巻線抵抗 [mΩ] (0 = CFG_COIL_MA を duty‰ として直接使う) */
#define CFG_ACCEL           40000u      /* 加速度 [マイクロステップ/s²] */
#define CFG_HOLD_PCT        40u         /* 停止中の保持電流 [%] */
#define CFG_HOLD_MS         500u        /* 停止してから保持電流に下げるまで [ms] */

/* 操作 */
#define CFG_RPM_PER_CLICK   10          /* エンコーダ 1 クリックの回転数 [rpm] */
#define CFG_DEMO_SPEED      8000u       /* 位置決めデモの最高速度 [マイクロステップ/s] */
#define CFG_LOG_MS          250u

